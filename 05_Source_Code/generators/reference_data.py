def _clean_author(authors: str) -> str:
    """Return an author string ending in exactly one period."""
    return authors.rstrip(".") + "."


def apa_reference(ref: dict) -> str:
    """Format one reference in APA 7th style using the verified metadata."""
    title = ref["title"].strip()
    title_end = "" if title.endswith(("?", "!")) else "."
    venue = ref["venue"].strip().rstrip(".")
    text = f"{_clean_author(ref['authors'])} ({ref['year']}). {title}{title_end} {venue}."
    if ref.get("doi"):
        text += f" https://doi.org/{ref['doi']}"
    elif ref.get("url"):
        text += f" {ref['url']}"
    return text


